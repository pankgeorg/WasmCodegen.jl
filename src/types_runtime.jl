# Run-time type information: predicates testing type ids against abstract types, generated
# once the module is complete (when all the concrete types of the closed world have ids).

"""
    isa_predicate!(cgm, T) -> Func

The function `(typeid::i32) -> i32` testing whether a type id is that of a subtype of
`T`. Its body is generated by [`finish_types!`](@ref).
"""
function isa_predicate!(cgm::CGModule, @nospecialize(T))
    get!(cgm.helpers, (:isa, T)) do
        add_func!(cgm.mod, string("jl_isa_", replace(string(T), r"[^A-Za-z0-9_]" => "_")),
                  ValType[I32], ValType[I32])
    end
end

function finish_types!(cgm::CGModule)
    for (key, f) in cgm.helpers
        key isa Tuple && key[1] === :isa || continue
        T = key[2]
        ids = Int32[id for (S, id) in cgm.types.typeids if S <: T]
        b = Builder(cgm.mod, f)
        if isempty(ids)
            emit!(b, :i32_const, 0)
        else
            for (i, id) in enumerate(sort(ids))
                emit!(b, :local_get, 0)
                emit!(b, :i32_const, id)
                emit!(b, :i32_eq)
                i > 1 && emit!(b, :i32_or)
            end
        end
        finish!(b)
    end
end

"""
    object_hash_func!(cgm) -> Func

The function `(obj::\$JlValue) -> i32` returning the identity hash of an object, assigned
on first use from a counter (the `hash` field of the header; 0 means unassigned).
"""
function object_hash_func!(cgm::CGModule)
    get!(cgm.helpers, :object_hash) do
        ts = cgm.types
        counter = add_global!(cgm.mod, "jl_hash_counter", I32, true, Inst[Inst(:i32_const, 0)])
        f = add_func!(cgm.mod, "jl_object_hash", ValType[jlvalue_ref(ts)], ValType[I32])
        b = Builder(cgm.mod, f)
        emit!(b, :local_get, 0)
        emit!(b, :struct_get, ts.jlvalue, 1)
        emit!(b, :i32_eqz)
        if!(b)
        emit!(b, :local_get, 0)
        emit!(b, :global_get, counter)
        emit!(b, :i32_const, 1)
        emit!(b, :i32_add)
        emit!(b, :global_set, counter)
        emit!(b, :global_get, counter)
        emit!(b, :struct_set, ts.jlvalue, 1)
        end!(b)
        emit!(b, :local_get, 0)
        emit!(b, :struct_get, ts.jlvalue, 1)
        finish!(b)
        f
    end
end

"""
    bytes_egal_func!(cgm) -> Func

`jl_bytes_egal(a, b) -> i32`: whether two byte arrays (of strings, symbols) have the same
bytes, which is `===` of strings (Julia compares them by content).
"""
function bytes_egal_func!(cgm::CGModule)
    get!(cgm.helpers, :bytes_egal) do
        arr = array_type!(cgm.types, I8)
        at = RefType(arr, true)
        f = add_func!(cgm.mod, "jl_bytes_egal", ValType[at, at], ValType[I32])
        b = Builder(cgm.mod, f)
        i, n = add_local!(f, I32), add_local!(f, I32)
        emit!(b, :local_get, 0); emit!(b, :local_get, 1); emit!(b, :ref_eq)
        if!(b); emit!(b, :i32_const, 1); return!(b); end!(b)
        emit!(b, :local_get, 0); emit!(b, :array_len); emit!(b, :local_set, n)
        emit!(b, :local_get, n); emit!(b, :local_get, 1); emit!(b, :array_len); emit!(b, :i32_ne)
        if!(b); emit!(b, :i32_const, 0); return!(b); end!(b)
        block!(b); loop!(b)
        emit!(b, :local_get, i); emit!(b, :local_get, n); emit!(b, :i32_ge_u)
        br_if!(b, 1)
        emit!(b, :local_get, 0); emit!(b, :local_get, i); emit!(b, :array_get_u, arr)
        emit!(b, :local_get, 1); emit!(b, :local_get, i); emit!(b, :array_get_u, arr)
        emit!(b, :i32_ne)
        if!(b); emit!(b, :i32_const, 0); return!(b); end!(b)
        emit!(b, :local_get, i); emit!(b, :i32_const, 1); emit!(b, :i32_add); emit!(b, :local_set, i)
        br!(b, 0)
        end!(b); end!(b)
        emit!(b, :i32_const, 1)
        finish!(b)
        f
    end
end

"Push the identity hash (an i32) of the object `x`."
function push_object_hash!(fc::FnCtx, x::CGVal)
    push_val!(fc, x)
    call!(fc.b, object_hash_func!(fc.cgm))
end

"""
Memory has no address on Wasm: each Memory object gets a virtual range of addresses, from
its identity hash shifted by 32 bits, so that the pointer comparisons Base makes (alias
checks, `dataids`) work. Pointers cannot be dereferenced.
"""
function push_memory_base!(fc::FnCtx, mem::CGVal)
    push_object_hash!(fc, mem)
    emit!(fc.b, :i64_extend_i32_u)
    emit!(fc.b, :i64_const, 32)
    emit!(fc.b, :i64_shl)
end

"""
    current_task_global!(cgm) -> Global

The task the module's code runs in (`current_task()`): a `Task` object, its fields zero
or empty but for its random number generator's state (`rngState0` ... `rngState4`), seeded
at start from the host (`julia.entropy`), as Julia seeds the root task from the system's
entropy.
"""
function current_task_global!(cgm::CGModule)
    g = get(cgm.helpers, :current_task, nothing)
    g === nothing || return g::Global
    ts = cgm.types
    l = layout(ts, Task)
    init = Inst[Inst(:i32_const, typeid!(ts, Task)), Inst(:i32_const, 0)]
    fields = (typedef(cgm.mod, l.wtype).comp::StructType).fields
    for f in fields[HEADER_FIELDS+1:end]
        st = f.storage
        push!(init, default_inst(st isa PackedType ? I32 : st))
    end
    push!(init, Inst(:struct_new, l.wtype))
    g = add_global!(cgm.mod, "jl_current_task", RefType(l.wtype, false), false, init)
    cgm.helpers[:current_task] = g
    # a new task holds `nothing` (not a null reference) in its Any-typed fields (storage, result,
    # scope, logstate, ...), so that `task_local_storage` creates its IdDict as natively
    nothing_g = singleton_global!(cgm.image, Nothing)
    for k in 1:fieldcount(Task)
        fieldtype(Task, k) === Any || continue
        w = first(l.fields[k]) - 1
        push!(cgm.image.init, Inst(:global_get, g), Inst(:global_get, nothing_g), Inst(:struct_set, l.wtype, w))
    end
    entropy = host_import!(cgm, "entropy", ValType[], ValType[I64])
    for i in 0:4
        w = first(l.fields[Base.fieldindex(Task, Symbol("rngState", i))]) - 1
        push!(cgm.image.init, Inst(:global_get, g), Inst(:call, entropy), Inst(:struct_set, l.wtype, w))
    end
    return g
end

"""
    objectid_mutable_func!(cgm) -> Func

`(x::\$JlValue) -> i64`: the `objectid` of the mutable object `x`. An object of the image has
the one it had natively (its header's hash is -k for the k-th of the image's native ids),
so that hash tables built at compile time find their keys; another one, a hash of its
identity hash (natively of its address). Generated when the image is complete.
"""
objectid_mutable_func!(cgm::CGModule) = get!(cgm.helpers, :objectid_mutable) do
    add_func!(cgm.mod, "jl_objectid_mutable", ValType[jlvalue_ref(cgm.types)], ValType[I64])
end

function finish_objectid!(cgm::CGModule)
    f = get(cgm.helpers, :objectid_mutable, nothing)
    f === nothing && return
    ids = cgm.image.native_ids
    ts = cgm.types
    i64s = array_type!(ts, I64)
    seg = add_data!(cgm.mod, isempty(ids) ? zeros(UInt8, 8) : collect(reinterpret(UInt8, ids)))
    g = add_global!(cgm.mod, "jl_native_ids", RefType(i64s, true), true, Inst[Inst(:ref_null, i64s)])
    b = Builder(cgm.mod, f)
    h = add_local!(f, I32)
    k = add_local!(f, I64)
    emit!(b, :local_get, 0); call!(b, object_hash_func!(cgm)); emit!(b, :local_tee, h)
    emit!(b, :i32_const, 0); emit!(b, :i32_lt_s)
    if!(b)
    emit!(b, :global_get, g); emit!(b, :ref_is_null)
    if!(b)
    emit!(b, :i32_const, 0); emit!(b, :i32_const, max(1, length(ids))); emit!(b, :array_new_data, i64s, seg)
    emit!(b, :global_set, g)
    end!(b)
    emit!(b, :global_get, g)
    emit!(b, :i32_const, -1); emit!(b, :local_get, h); emit!(b, :i32_sub)   # -h - 1
    emit!(b, :array_get, i64s)
    return!(b)
    end!(b)
    # int64hash(h) (Thomas Wang's, as `objectid`'s)
    emit!(b, :local_get, h); emit!(b, :i64_extend_i32_u); emit!(b, :local_set, k)
    step!(op1, sh, op2) = begin
        emit!(b, :local_get, k)
        emit!(b, :local_get, k); emit!(b, :i64_const, sh); emit!(b, op1)
        emit!(b, op2); emit!(b, :local_set, k)
    end
    # key = (~key) + (key << 21)
    emit!(b, :local_get, k); emit!(b, :i64_const, -1); emit!(b, :i64_xor)
    emit!(b, :local_get, k); emit!(b, :i64_const, 21); emit!(b, :i64_shl); emit!(b, :i64_add); emit!(b, :local_set, k)
    step!(:i64_shr_u, 24, :i64_xor)                        # key ^ (key >> 24)
    # key = (key + (key << 3)) + (key << 8)
    emit!(b, :local_get, k); emit!(b, :local_get, k); emit!(b, :i64_const, 3); emit!(b, :i64_shl); emit!(b, :i64_add)
    emit!(b, :local_get, k); emit!(b, :i64_const, 8); emit!(b, :i64_shl); emit!(b, :i64_add); emit!(b, :local_set, k)
    step!(:i64_shr_u, 14, :i64_xor)                        # key ^ (key >> 14)
    # key = (key + (key << 2)) + (key << 4)
    emit!(b, :local_get, k); emit!(b, :local_get, k); emit!(b, :i64_const, 2); emit!(b, :i64_shl); emit!(b, :i64_add)
    emit!(b, :local_get, k); emit!(b, :i64_const, 4); emit!(b, :i64_shl); emit!(b, :i64_add); emit!(b, :local_set, k)
    step!(:i64_shr_u, 28, :i64_xor)                        # key ^ (key >> 28)
    step!(:i64_shl, 31, :i64_add)                          # key + (key << 31)
    emit!(b, :local_get, k)
    finish!(b)
end

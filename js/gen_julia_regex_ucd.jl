# PCRE2's Unicode data as the julia_regex translator needs it: the sets of code points of every
# property, generic type and POSIX class, as native PCRE2 (10.47, Unicode 16)
# matches them, so that translated patterns don't depend on V8's Unicode version.
# usage: julia js/gen_julia_regex_ucd.jl (writes js/julia_regex_ucd.mjs)
function pcre_config_string(what::UInt32)
    n = ccall((:pcre2_config_8, Base.PCRE.PCRE_LIB), Cint, (UInt32, Ptr{UInt8}), what, C_NULL)
    n > 0 || error("PCRE2 config query failed: $n")
    buf = Vector{UInt8}(undef, n)
    r = ccall((:pcre2_config_8, Base.PCRE.PCRE_LIB), Cint, (UInt32, Ptr{UInt8}), what, buf)
    r == n || error("PCRE2 config query failed: $r")
    return String(buf[1:end-1])
end
const PCRE_VERSION = pcre_config_string(Base.PCRE.CONFIG_VERSION)
const UNICODE_VERSION = pcre_config_string(Base.PCRE.CONFIG_UNICODE_VERSION)
startswith(PCRE_VERSION, "10.47 ") || error("Expected PCRE2 10.47, got $PCRE_VERSION")
UNICODE_VERSION == "16.0.0" || error("Expected Unicode 16.0.0, got $UNICODE_VERSION")

const OUT = joinpath(@__DIR__, "julia_regex_ucd.mjs")

const CPS = [cp for cp in 0:0x10ffff if !(0xd800 <= cp <= 0xdfff)]
const STRS = [string(Char(cp)) for cp in CPS]

function ranges_of(hit::BitVector)
    out = Tuple{Int,Int}[]
    lo = -1; prev = -2
    for (k, cp) in enumerate(CPS)
        if hit[k]
            if lo >= 0 && cp == prev + 1
                prev = cp
            else
                lo >= 0 && push!(out, (lo, prev))
                lo = prev = cp
            end
        end
    end
    lo >= 0 && push!(out, (lo, prev))
    return out
end
# runs (lo..hi) merged across the surrogate gap is not needed: the translator never sees surrogates

function set_of(p::String, flags::String="")
    re = Regex("\\A(?:" * p * ")\\z", flags)
    return ranges_of(BitVector([occursin(re, s) for s in STRS]))
end

sets = Pair{String,Vector{Tuple{Int,Int}}}[]
add!(name, p, flags="") = (push!(sets, name => set_of(p, flags)); @info name length(last(sets[end])))

# general categories
for gc in ["Cc", "Cf", "Cn", "Co", "Ll", "Lm", "Lo", "Lt", "Lu", "Mc", "Me", "Mn", "Nd", "Nl", "No",
           "Pc", "Pd", "Pe", "Pf", "Pi", "Po", "Ps", "Sc", "Sk", "Sm", "So", "Zl", "Zp", "Zs"]
    add!("gc:" * gc, "\\p{" * gc * "}")
end
# caseless forms that PCRE2 case-closes
for gc in ["Lu", "Ll", "Lt"]
    add!("gci:" * gc, "\\p{" * gc * "}", "i")
end
# special properties
for p in ["Xan", "Xps", "Xsp", "Xwd", "Xuc", "L&"]
    add!("x:" * p, "\\p{" * p * "}")
end
# generic types (UCP, and the UTF-without-UCP forms of \h \v that are Unicode anyway)
for e in ["d", "w", "s", "h", "v"]
    add!("ucp:" * e, "\\" * e)
end
# POSIX classes, UCP
for c in ["alnum", "alpha", "blank", "cntrl", "digit", "graph", "lower", "print", "punct", "space", "upper", "word", "xdigit"]
    add!("posix:" * c, "[[:" * c * ":]]")
end
# scripts: Script (sc:) and the bare name (Script Extensions)
scripts = String[]
for line in eachline(joinpath(@__DIR__, "julia_regex_scripts.txt"))
    name = strip(line)
    isempty(name) && continue
    try
        Regex("\\p{sc:" * name * "}")
        push!(scripts, name)
    catch
        @warn "not a PCRE2 script" name
    end
end
for name in scripts
    add!("sc:" * name, "\\p{sc:" * name * "}")
    add!("scx:" * name, "\\p{" * name * "}")
end

open(OUT, "w") do io
    println(io, "// PCRE2 $(first(split(PCRE_VERSION))) (Julia $VERSION) Unicode $UNICODE_VERSION property sets for julia_regex.mjs: GENERATED by")
    println(io, "// gen_julia_regex_ucd.jl from native PCRE2 on every code point. Do not edit.")
    println(io, "// Each set is a string of hex range pairs \"lo-hi lo-hi ...\" (single points as \"lo\").")
    println(io, "export const UCD_UNICODE_VERSION = '$UNICODE_VERSION';")
    println(io, "export const UCD = {")
    for (name, rs) in sets
        enc = join((a == b ? string(a, base=16) : string(a, base=16) * "-" * string(b, base=16) for (a, b) in rs), " ")
        println(io, "  ", repr(name), ": '", enc, "',")
    end
    println(io, "};")
end
@info "wrote" OUT length(sets)
